// Writes the double-click scripts with Windows line endings (cmd.exe can misread Unix ones). Run it after changing them:
// node tools/write-bats.mjs

import { writeFileSync } from "node:fs";

const needNode = `where node >nul 2>nul || (echo Node.js is not installed. Get it from nodejs.org, then run this again. & pause & exit /b 1)`;
const needRust = `where cargo >nul 2>nul || (echo Rust is not installed. Get it from rustup.rs, then run this again. & pause & exit /b 1)`;
const install = `if not exist node_modules (call npm.cmd install || (pause & exit /b 1))`;
const buildIfMissing = [
  `if not exist studio-helper\\target\\release\\studio-helper.exe goto build`,
  `if not exist src-tauri\\target\\release\\openstage-studio.exe goto build`,
  `goto built`,
  `:build`,
  `echo OpenStage Studio is not built yet. Building it now; the first time takes several minutes.`,
  `call "%~dp0Build Studio.bat" nopause || (pause & exit /b 1)`,
  `:built`,
];

const scripts = {
  "Build Studio.bat": [
    "@echo off",
    "title Build OpenStage Studio",
    'cd /d "%~dp0"',
    needNode,
    needRust,
    "echo Checking that everything OpenStage Studio needs is installed.",
    "call npm.cmd install || (pause & exit /b 1)",
    "echo.",
    "echo Building the helper: the part that records windows, speaks narration and writes the video.",
    "cargo build --release --manifest-path studio-helper\\Cargo.toml || (echo. & echo The helper did not build. Send the text above to the AI assistant. & if not \"%1\"==\"nopause\" pause & exit /b 1)",
    "echo.",
    "echo Building the app, with the practice program it records.",
    "call npx.cmd tauri build --no-bundle || (echo. & echo The app did not build. Send the text above to the AI assistant. & if not \"%1\"==\"nopause\" pause & exit /b 1)",
    "echo.",
    "echo OpenStage Studio is built.",
    'if not "%1"=="nopause" pause',
  ],
  "Run OpenStage Studio.bat": [
    "@echo off",
    "title OpenStage Studio",
    'cd /d "%~dp0"',
    needNode,
    needRust,
    "echo Checking that everything OpenStage Studio needs is installed. This takes a few minutes the first time.",
    "call npm.cmd install || (pause & exit /b 1)",
    "echo.",
    "call npm.cmd run tauri -- dev",
    "pause",
  ],
  "Make Video.bat": [
    "@echo off",
    "title OpenStage Studio: make a video",
    'cd /d "%~dp0"',
    needNode,
    install,
    ...buildIfMissing,
    'set "SCRIPT=%~1"',
    'if "%SCRIPT%"=="" set "SCRIPT=examples\\plan-a-lesson.json"',
    "echo Making a video of %SCRIPT%",
    "echo (To make a video of another script, drag its .json file onto this file.)",
    "echo.",
    "echo The program being recorded fills one screen for a minute or two: the main one, or the one local-settings.json names.",
    "echo You can leave it running; it ignores the mouse and the keyboard, and closes by itself when the take is done.",
    "echo The first time, narration needs the voice: run Get Voice.bat once first.",
    "echo.",
    'node src\\pipeline\\make-video.ts "%SCRIPT%" || (pause & exit /b 1)',
    "echo.",
    'for %%F in ("%SCRIPT%") do set "NAME=%%~nF"',
    'if exist "renders\\%NAME%" start "" "renders\\%NAME%"',
    "pause",
  ],
  "Get Voice.bat": [
    "@echo off",
    "title OpenStage Studio: get the narration voice",
    'cd /d "%~dp0"',
    needNode,
    install,
    "node src\\pipeline\\get-voice.ts",
    "pause",
  ],
  "Check Same Video.bat": [
    "@echo off",
    "title OpenStage Studio: check that a script gives the same video twice",
    'cd /d "%~dp0"',
    needNode,
    install,
    ...buildIfMissing,
    'set "SCRIPT=%~1"',
    'if "%SCRIPT%"=="" set "SCRIPT=examples\\plan-a-lesson.json"',
    "echo This makes the video of %SCRIPT% twice, from scratch each time, and checks that both are the same.",
    "echo It takes about ten minutes. The program being recorded fills one screen during each take (see local-settings.json).",
    "echo.",
    'node src\\pipeline\\check-repeat.ts "%SCRIPT%"',
    "echo.",
    "pause",
  ],
  "Test Everything.bat": [
    "@echo off",
    "title OpenStage Studio tests",
    'cd /d "%~dp0"',
    needNode,
    needRust,
    install,
    "echo Checking the TypeScript.",
    "call npx.cmd tsc --noEmit || (echo The TypeScript check FAILED. & pause & exit /b 1)",
    "echo.",
    "echo Running the TypeScript tests.",
    "call npm.cmd test || (echo The TypeScript tests FAILED. & pause & exit /b 1)",
    "echo.",
    "echo Running the helper's tests.",
    "cargo test --release --manifest-path studio-helper\\Cargo.toml || (echo The helper's tests FAILED. & pause & exit /b 1)",
    "echo.",
    "echo All the tests passed.",
    "pause",
  ],
  "Check Licences.bat": [
    "@echo off",
    "title OpenStage Studio licence check",
    'cd /d "%~dp0"',
    needNode,
    install,
    "node tools\\check-licences.mjs",
    "pause",
  ],
  "Make App Icons.bat": [
    "@echo off",
    "title OpenStage Studio: make the app icons",
    'cd /d "%~dp0"',
    needNode,
    "if exist OpenStage_Studio_Icon.zip (",
    "  echo Unpacking OpenStage_Studio_Icon.zip into the branding folder.",
    "  powershell -NoProfile -Command \"Expand-Archive -LiteralPath 'OpenStage_Studio_Icon.zip' -DestinationPath 'branding' -Force\" || (pause & exit /b 1)",
    ")",
    "node tools\\make-icons.mjs branding || (pause & exit /b 1)",
    "pause",
  ],
};

for (const [name, lines] of Object.entries(scripts)) writeFileSync(name, lines.join("\r\n") + "\r\n");
console.log(`Wrote ${Object.keys(scripts).length} scripts.`);
